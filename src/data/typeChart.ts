export interface DefensiveMatchupGroup {
  multiplier: number;
  label: string;
  types: PokemonType[];
}

const MULTIPLIER_ORDER: Array<{ multiplier: number; label: string }> = [
  { multiplier: 4, label: '4x Weak' },
  { multiplier: 2, label: '2x Weak' },
  { multiplier: 0.5, label: '0.5x Resist' },
  { multiplier: 0.25, label: '0.25x Resist' },
  { multiplier: 0, label: '0x Immune' },
];

/**
 * Calculates incoming defensive damage multipliers against a given Pokémon's type combination.
 * Returns attacking types grouped by multiplier, ordered by severity (4x down to 0x), omitting empty groups.
 */
export function getDefensiveMatchups(
  type1: PokemonType,
  type2?: PokemonType | null
): DefensiveMatchupGroup[] {
  const grouped: Record<number, PokemonType[]> = {
    4: [],
    2: [],
    0.5: [],
    0.25: [],
    0: [],
  };

  for (const atkType of POKEMON_TYPES) {
    const mult1 = TYPE_CHART[atkType]?.[type1] ?? 1;
    const mult2 = type2 ? TYPE_CHART[atkType]?.[type2] ?? 1 : 1;
    const totalMult = mult1 * mult2;

    if (totalMult in grouped) {
      grouped[totalMult].push(atkType);
    }
  }

  return MULTIPLIER_ORDER.filter((group) => grouped[group.multiplier].length > 0).map(
    (group) => ({
      multiplier: group.multiplier,
      label: group.label,
      types: grouped[group.multiplier],
    })
  );
}
